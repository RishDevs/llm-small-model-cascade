import json

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

from cascade.calibration import fit_temperature, reliability, softmax, summary
from cascade.config import base_parser, load_config
from cascade.data import OOS, load_clinc, split_arrays, teacher_labels
from cascade.routing import accuracy_curve, pick_threshold, route
from cascade.student import Student


def pct(x):
    return round(100 * float(x), 2)


def accuracy_block(pred, gold, oos):
    inscope = gold != oos
    return {
        "accuracy": pct((pred == gold).mean()),
        "in_scope_accuracy": pct((pred[inscope] == gold[inscope]).mean()),
        "oos_recall": pct((pred[~inscope] == oos).mean()),
    }


def plot_reliability(raw, cal, y, bins, path):
    fig, ax = plt.subplots(figsize=(5, 5))
    ax.plot([0, 1], [0, 1], color="0.6", lw=1, ls="--")
    for probs, name in ((raw, "before"), (cal, "after")):
        rows = reliability(probs, y, bins)
        ax.plot([r[0] for r in rows], [r[1] for r in rows], marker="o", label=name)
    ax.set_xlabel("confidence")
    ax.set_ylabel("agreement with teacher")
    ax.set_title("Student reliability (test)")
    ax.legend()
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)


def plot_coverage(coverage, acc, teacher_acc, chosen, path):
    fig, ax = plt.subplots(figsize=(6, 4))
    ax.plot(coverage * 100, acc * 100, label="cascade")
    ax.axhline(teacher_acc * 100, color="0.5", ls="--", lw=1, label="teacher only")
    ax.scatter([chosen[0] * 100], [chosen[1] * 100], color="black", zorder=3, label="chosen threshold")
    ax.set_xlabel("handled by student (%)")
    ax.set_ylabel("accuracy vs gold (%)")
    ax.set_title("Coverage vs accuracy (test)")
    ax.legend()
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)


def change(reduction):
    if reduction is None:
        return "n/a"
    return f"{reduction}% lower" if reduction >= 0 else f"{-reduction}% higher"


def results_md(m):
    t, s, c = m["test"]["teacher"], m["test"]["student"], m["test"]["cascade"]
    cal = m["calibration_vs_teacher"]
    lines = [
        "# Results",
        "",
        f"Generated by `python -m cascade.evaluate` from `{m['onnx']}`. Test split: {m['test']['n']} utterances.",
        "",
        "| | Teacher only | Student only | Cascade |",
        "|---|---|---|---|",
        f"| Accuracy (gold) | {t['accuracy']}% | {s['accuracy']}% | {c['accuracy']}% |",
        f"| In-scope accuracy | {t['in_scope_accuracy']}% | {s['in_scope_accuracy']}% | {c['in_scope_accuracy']}% |",
        f"| OOS recall | {t['oos_recall']}% | {s['oos_recall']}% | {c['oos_recall']}% |",
        f"| LLM calls | 100% | 0% | {round(100 - m['test']['coverage'], 2)}% |",
        "",
        f"- LLM calls avoided: **{m['test']['coverage']}%**",
        f"- Cascade vs teacher accuracy: **{m['test']['gap_pp']:+} pp**",
        f"- OOS recall, cascade vs student alone: **{m['test']['oos_recall_gain_pp']:+} pp**",
        f"- ECE vs teacher labels: {cal['before']['ece']} -> {cal['after']['ece']} "
        f"(**{change(cal['ece_reduction_pct'])}**), temperature {m['temperature']}",
        f"- Threshold {m['threshold']} picked on validation with a {m['max_disagreement'] * 100}% disagreement budget",
    ]
    return "\n".join(lines) + "\n"


def main():
    parser = base_parser("Calibrate, pick the routing threshold, and score the cascade")
    parser.add_argument("--fp32", action="store_true")
    args = parser.parse_args()

    cfg = load_config(args.config)
    paths = cfg["paths"]
    bins = cfg["routing"]["ece_bins"]
    budget = cfg["routing"]["max_disagreement"]
    onnx_path = paths["onnx_fp32"] if args.fp32 else paths["onnx_int8"]

    ds, labels = load_clinc(cfg)
    oos = labels.index(OOS)
    student = Student(paths["student_dir"], onnx_path, cfg["student"]["max_length"])

    split = {}
    for name in ("validation", "test"):
        texts, gold = split_arrays(ds, name)
        teacher = np.array(teacher_labels(paths["teacher_dir"], name, labels, len(texts)))
        if (teacher < 0).mean() > 0.01:
            raise SystemExit(f"{name}: {int((teacher < 0).sum())} utterances have no teacher label - finish cascade.teacher")
        split[name] = {"gold": np.array(gold), "teacher": teacher, "logits": student.logits(texts)}

    val = split["validation"]
    known = val["teacher"] >= 0
    temperature = fit_temperature(val["logits"][known], val["teacher"][known])
    val_probs = softmax(val["logits"], temperature)
    threshold = pick_threshold(val_probs.max(1), val_probs.argmax(1), val["teacher"], budget)
    val_accept = val_probs.max(1) >= threshold
    val_disagree = (val_accept & (val_probs.argmax(1) != val["teacher"])).mean()

    test = split["test"]
    raw = softmax(test["logits"])
    cal = softmax(test["logits"], temperature)
    conf, pred = cal.max(1), cal.argmax(1)
    final, accepted = route(pred, conf, test["teacher"], threshold)
    gold, teacher = test["gold"], test["teacher"]

    known = teacher >= 0
    before_t, after_t = summary(raw[known], teacher[known], bins), summary(cal[known], teacher[known], bins)
    before_g, after_g = summary(raw, gold, bins), summary(cal, gold, bins)

    blocks = {
        "teacher": accuracy_block(teacher, gold, oos),
        "student": accuracy_block(pred, gold, oos),
        "cascade": accuracy_block(final, gold, oos),
    }
    metrics = {
        "onnx": onnx_path.name,
        "temperature": round(temperature, 4),
        "threshold": round(threshold, 6) if np.isfinite(threshold) else None,
        "max_disagreement": budget,
        "validation": {"coverage": pct(val_accept.mean()), "disagreement": pct(val_disagree)},
        "test": {
            "n": int(len(gold)),
            "coverage": pct(accepted.mean()),
            "gap_pp": round(blocks["cascade"]["accuracy"] - blocks["teacher"]["accuracy"], 2),
            "oos_recall_gain_pp": round(blocks["cascade"]["oos_recall"] - blocks["student"]["oos_recall"], 2),
            "student_teacher_agreement": pct((pred == teacher).mean()),
            "cascade_teacher_agreement": pct((final == teacher).mean()),
            "escalated_oos_share": pct((gold[~accepted] == oos).mean()) if (~accepted).any() else None,
            **blocks,
        },
        "calibration_vs_teacher": {
            "before": before_t,
            "after": after_t,
            "ece_reduction_pct": pct(1 - after_t["ece"] / before_t["ece"]) if before_t["ece"] else None,
        },
        "calibration_vs_gold": {
            "before": before_g,
            "after": after_g,
            "ece_reduction_pct": pct(1 - after_g["ece"] / before_g["ece"]) if before_g["ece"] else None,
        },
    }

    reports = paths["reports"]
    reports.mkdir(parents=True, exist_ok=True)
    (reports / "metrics.json").write_text(json.dumps(metrics, indent=2))
    (reports / "RESULTS.md").write_text(results_md(metrics))
    plot_reliability(raw[known], cal[known], teacher[known], bins, reports / "reliability.png")
    coverage, acc = accuracy_curve(conf, pred, teacher, gold)
    plot_coverage(
        coverage, acc, (teacher == gold).mean(), (accepted.mean(), (final == gold).mean()), reports / "coverage.png"
    )
    paths["routing"].write_text(
        json.dumps({"temperature": temperature, "threshold": threshold if np.isfinite(threshold) else None, "onnx": onnx_path.name}, indent=2)
    )
    print((reports / "RESULTS.md").read_text())


if __name__ == "__main__":
    main()
